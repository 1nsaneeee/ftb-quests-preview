import { mkdir, readFile, readdir, stat, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const projectDir = resolve(fileURLToPath(new URL("..", import.meta.url)));
const outdir = join(projectDir, "editor-assets");
const outfile = join(outdir, "description-editor.bundle.js");
const licensesFile = join(outdir, "LICENSES.txt");

await mkdir(outdir, { recursive: true });

const result = await build({
  entryPoints: [join(projectDir, "components", "description-editor.js")],
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  minify: true,
  sourcemap: false,
  legalComments: "none",
  outfile,
  metafile: true,
  logLevel: "warning",
});

const packageNames = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  const normalized = input.replaceAll("\\", "/");
  const match = normalized.match(/node_modules\/((?:@[^/]+\/)?[^/]+)\//);
  if (match) packageNames.add(match[1]);
}

const packages = [];
for (const name of [...packageNames].sort()) {
  const packageDir = join(projectDir, "node_modules", ...name.split("/"));
  let metadata;
  try {
    metadata = JSON.parse(await readFile(join(packageDir, "package.json"), "utf8"));
  } catch {
    continue;
  }
  const licenseText = await readLicenseText(packageDir);
  packages.push({ name, license: metadata.license ?? "UNKNOWN", version: metadata.version ?? "", licenseText });
}

const header = [
  "Third-party software bundled into editor-assets/description-editor.bundle.js",
  "Generated by scripts/build-editor.mjs. Do not edit by hand.",
  "",
  ...packages.map(entry => `- ${entry.name}@${entry.version} (${entry.license})`),
  "",
].join("\n");
const body = packages
  .filter(entry => entry.licenseText)
  .map(entry => `===== ${entry.name}@${entry.version} — ${entry.license} =====\n\n${entry.licenseText.trim()}\n`)
  .join("\n");
await writeFile(licensesFile, `${header}\n${body}`);

const bundleStat = await stat(outfile);
console.log(`Built ${outfile} (${Math.round(bundleStat.size / 1024)} KiB, ${packages.length} bundled license entries).`);
console.log(`Wrote ${licensesFile}.`);

async function readLicenseText(packageDir) {
  let entries;
  try {
    entries = await readdir(packageDir);
  } catch {
    return "";
  }
  const candidate = entries
    .filter(name => /^licen[cs]e(\.(md|txt))?$/i.test(name))
    .sort((a, b) => a.localeCompare(b))[0];
  if (!candidate) return "";
  try {
    const text = await readFile(join(packageDir, candidate), "utf8");
    return text.length > 8000 ? `${text.slice(0, 8000)}\n…` : text;
  } catch {
    return "";
  }
}
